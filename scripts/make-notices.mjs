// Generates THIRD-PARTY-NOTICES.md from the licence files and package.json fields
// of the installed runtime dependencies. Nothing here is typed by hand: if a
// package ships no licence text, the notice says so instead of inventing one.
import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";

const PKGS = [
  "@contentauth/c2pa-web",
  "@contentauth/c2pa-wasm",
  "@contentauth/c2pa-types",
  "@contentauth/c2pa-utilities",
  "highgain",
  "ts-deepmerge",
];

const out = [];
out.push("# Third-party notices", "");
out.push(
  "This package depends on the components below. The text is generated by `scripts/make-notices.mjs` from the installed packages' own licence files and `package.json` fields.",
  "",
);

const texts = new Map();
for (const name of PKGS) {
  const dir = `node_modules/${name}`;
  const pkg = JSON.parse(readFileSync(`${dir}/package.json`, "utf8"));
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)/i.test(f));
  const text = file ? readFileSync(`${dir}/${file}`, "utf8").trim() : null;
  // Names only: contact addresses in package metadata are not copied into this repository.
  const rawAuthor = typeof pkg.author === "string" ? pkg.author : pkg.author?.name ?? null;
  const author = rawAuthor ? rawAuthor.replace(/\s*<[^>]*>/, "").trim() : null;
  out.push(`## ${name} ${pkg.version}`, "");
  out.push(`- package.json license field: ${pkg.license ?? "(none declared)"}`);
  if (author) out.push(`- author field: ${author}`);
  if (text) {
    const h = createHash("sha256").update(text).digest("hex").slice(0, 12);
    if (!texts.has(h)) texts.set(h, { text, names: [] });
    texts.get(h).names.push(name);
    out.push(`- licence text: ${file} (shipped in the package; reproduced below, ref ${h})`);
  } else {
    out.push("- licence text: the package ships none. Only the licence name above is declared in its package.json; the copyright year is not stated.");
  }
  out.push("");
}

out.push("## Licence texts", "");
for (const [h, { text, names }] of texts) {
  out.push(`### Ref ${h} — ${names.join(", ")}`, "", "```", text, "```", "");
}

out.push(
  "## The WebAssembly binary (`dist/c2pa.wasm`)",
  "",
  "`c2pa.wasm` is the unmodified `c2pa_bg.wasm` from `@contentauth/c2pa-web` (copied from its `resources/c2pa.wasm` export). It is compiled from the Rust library c2pa-rs and its Rust dependencies. The upstream npm packages ship one Adobe MIT licence file and do not itemise the licences of the individual Rust crates compiled into the binary; this repository does not either, and has not independently audited them. The c2pa-rs repository declares `license = \"MIT OR Apache-2.0\"` in its `sdk/Cargo.toml` (read on the date this file was generated).",
  "",
);

writeFileSync("THIRD-PARTY-NOTICES.md", out.join("\n"));
console.log("wrote THIRD-PARTY-NOTICES.md; distinct licence texts:", texts.size);
